function defineVisibleCatalog(entries: ReadonlyArray<readonly [string, string]>): WorkbenchVisibleCatalog {
  const zh: Record<string, string> = {};
  const en: Record<string, string> = {};
  const englishByChinese: Record<string, string> = {};
  entries.forEach(([source, translated], index) => {
    const key = `v${String(index + 1).padStart(3, '0')}`;
    zh[key] = source;
    en[key] = translated;
    englishByChinese[source] = translated;
  });
  return { zh, en, englishByChinese };
}

