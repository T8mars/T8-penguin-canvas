export function localizeInspirationDynamicText(value: string) {
  const rules: Array<[RegExp, (...groups: string[]) => string]> = [
    [/^(\d+) 图 · (\d+) 视频$/, (images, videos) => `${images} images · ${videos} videos`],
    [/^图 (\d+)$/, (index) => `Image ${index}`],
    [/^视频 (\d+)$/, (index) => `Video ${index}`],
    [/^(\d+) 个镜头$/, (count) => `${count} shots`],
    [/^(\d+) 秒$/, (seconds) => `${seconds} sec`],
    [/^已接收 (\d+) 条上游文本，并与本地补充合并。$/, (count) => `Received ${count} upstream text item(s) and merged them with the local addition.`],
    [/^已从“创作意图”端口接收 (\d+) 条文本。$/, (count) => `Received ${count} text item(s) from the Creative Intent port.`],
    [/^(\d+) 次 LLM 请求$/, (count) => `${count} LLM requests`],
    [/^(\d+) 个匹配 · (\d+) 个自定义$/, (matches, custom) => `${matches} matches · ${custom} custom`],
    [/^第 (\d+) \/ (\d+) 页 · 共(约)? (\d+) 个$/, (page, totalPages, approximate, total) => `Page ${page} of ${totalPages} · ${approximate ? 'about ' : ''}${total} total`],
  ];
  for (const [pattern, render] of rules) {
    const match = value.match(pattern);
    if (match) return render(...match.slice(1));
  }
  return value;
}
